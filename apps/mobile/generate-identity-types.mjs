import { readFile, writeFile } from 'node:fs/promises';
import { parse } from 'yaml';

const source = new URL('../../docs/api/core/v1/paths/accounts.yaml', import.meta.url);
const paths = parse(await readFile(source, 'utf8'));
const operations = [
  '/accounts', '/email-verifications', '/email-verification-requests', '/auth/sessions',
  '/password-reset-requests', '/password-resets',
];

const entries = await Promise.all(operations.map(async path => {
  const { operationId, requestBody } = paths[path].post;
  const schemaUrl = new URL(requestBody.content['application/json'].schema.$ref, source);
  const schema = parse(await readFile(schemaUrl, 'utf8'));
  if (schema.type !== 'object' || schema.additionalProperties !== false) {
    throw new Error(`Unsupported JSON body type for ${operationId}`);
  }
  const properties = Object.entries(schema.properties).map(([name, property]) => {
    if (property.type !== 'string') throw new Error(`Unsupported type for ${operationId}.${name}`);
    const optional = schema.required.includes(name) ? '' : '?';
    return `    ${JSON.stringify(name)}${optional}: string;`;
  });
  return [`  ${operationId}: {`, ...properties, '  };'].join('\n');
}));

const sessionRef = paths['/auth/sessions'].post.responses[200].content['application/json'].schema.$ref;
const session = parse(await readFile(new URL(sessionRef, source), 'utf8'));
const sessionFields = Object.entries(session.properties).map(([name, property]) => {
  if (property.type !== 'string' || !session.required.includes(name)) {
    throw new Error(`Unsupported Session field ${name}`);
  }
  const literals = property.enum ?? (property.const ? [property.const] : null);
  return `  ${name}: ${literals ? literals.map(value => JSON.stringify(value)).join(' | ') : 'string'};`;
});

await writeFile(new URL('./identity-api.generated.ts', import.meta.url), [
  '// Generated by npm run generate:identity.', 'export interface IdentityRequests {', ...entries, '}', '',
  'export interface PasswordSession {', ...sessionFields, '}', '',
].join('\n'));
