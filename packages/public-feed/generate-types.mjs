import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';
import { parse } from 'yaml';

const directory = new URL('../../docs/api/core/v1/', import.meta.url);
const specUrl = new URL('openapi.yaml', directory);
const spec = parse(await readFile(specUrl, 'utf8'));
const { get } = parse(await readFile(new URL('paths/posts.yaml', directory), 'utf8'))['/posts'];
const response = get.responses[200].content['application/json'];
const schema = new URL(response.schema.$ref, new URL('paths/posts.yaml', directory));

const types = await openapiTS({
  openapi: spec.openapi,
  info: spec.info,
  paths: {
    '/posts': {
      get: {
        operationId: get.operationId,
        responses: {
          200: {
            description: get.responses[200].description,
            content: { 'application/json': { schema: { $ref: fileURLToPath(schema) } } },
          },
        },
      },
    },
  },
}, { cwd: specUrl });

await writeFile(
  new URL('./openapi.generated.ts', import.meta.url),
  '// Generated by npm run generate:feed.\n' + astToString(types),
);
